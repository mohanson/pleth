import io
import pleth


def test_tuple():
    k = pleth.abi.Tuple([
        pleth.abi.Uint256,
        pleth.abi.Tuple([pleth.abi.Uint256, pleth.abi.Uint256]),
        pleth.abi.String,
        pleth.abi.String,
    ])
    v = [0x123, [0x456, 0x789], '1234567890', 'Hello, world!']
    assert k.decode(io.BytesIO(bytes(k.encode(v)))) == v


